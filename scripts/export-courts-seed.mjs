#!/usr/bin/env node
// Generates supabase/seed.sql from assets/data/courts.json (the curated seed stays in JSON; the
// SQL is derived). Idempotent: `on conflict (id) do update`. No dependencies.
//   node scripts/export-courts-seed.mjs > supabase/seed.sql
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(join(root, 'assets/data/courts.json'), 'utf8'));
const q = (v) => v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const n = (v) => v === null || v === undefined ? 'null' : Number(v);

const lines = [];
lines.push(`-- Generated by scripts/export-courts-seed.mjs from assets/data/courts.json`);
lines.push(`-- courts.json metadata: version ${data.metadata.version}, last_updated ${data.metadata.last_updated}, metro ${data.metadata.metro}`);
lines.push(`insert into public.courts (id, metro, name, neighborhood, lat, lng, sports, tier, court_count, demand_tier, notes, source, is_active, last_updated) values`);
const rows = data.courts.map((c) => {
  const sports = `array[${c.sports.map(q).join(', ')}]::public.sport[]`;
  return `  (${q(c.id)}, ${q(c.metro || data.metadata.metro)}, ${q(c.name)}, ${q(c.neighborhood)}, ${n(c.lat)}, ${n(c.lng)}, ${sports}, ${q(c.tier)}::public.court_tier, ${n(c.court_count)}, ${q(c.demand_tier || 'medium')}::public.demand_tier, ${q(c.notes)}, 'curated', true, ${q(data.metadata.last_updated)}::date)`;
});
lines.push(rows.join(',\n'));
lines.push(`on conflict (id) do update set`);
lines.push(`  metro = excluded.metro, name = excluded.name, neighborhood = excluded.neighborhood, lat = excluded.lat, lng = excluded.lng,`);
lines.push(`  sports = excluded.sports, tier = excluded.tier, court_count = excluded.court_count, demand_tier = excluded.demand_tier,`);
lines.push(`  notes = excluded.notes, last_updated = excluded.last_updated, updated_at = now();`);
process.stdout.write(lines.join('\n') + '\n');
